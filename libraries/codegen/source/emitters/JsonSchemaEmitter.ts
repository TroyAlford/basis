import type { EffectiveFieldDefinition, EntityDefinition, FieldDefinition, Graph, ScalarFieldDefinition } from 'basis/server'
import { FieldType, SNOWFLAKE_IDENTITY_PATTERN, UUID_IDENTITY_PATTERN } from 'basis/server'
import type { EmittedFile } from '../emitter'
import { emitter } from '../emitter'

/** Generated JSON Schema by entity and operation. */
export type GeneratedSchemas = Readonly<Record<string, {
  /** Input schema for creates. */
  readonly create: Readonly<Record<string, unknown>>,
  /** Hydrated output schema. */
  readonly output: Readonly<Record<string, unknown>>,
  /** Input schema for updates. */
  readonly update: Readonly<Record<string, unknown>>,
}>>

/** One schema operation kind. */
type SchemaKind = 'create' | 'output' | 'update'

/** Fields generated by the root or update tracking, never writable. */
const GENERATED_FIELDS = new Set(['entity', 'lastUpdatedAt', 'lastUpdatedBy'])

/**
 * Generate deterministic, reusable JSON Schemas for every entity.
 * @param graph - Canonical application Graph.
 * @returns JSON Schema by entity and operation.
 */
export function generateJSONSchemas(graph: Graph): GeneratedSchemas {
  const definitions = graph.definitions
  const schemas: Record<string, {
    create: Readonly<Record<string, unknown>>,
    output: Readonly<Record<string, unknown>>,
    update: Readonly<Record<string, unknown>>,
  }> = {}
  for (const entity of definitions.entities) {
    schemas[entity.name] = {
      create: entitySchema(entity, 'create', definitions),
      output: entitySchema(entity, 'output', definitions),
      update: entitySchema(entity, 'update', definitions),
    }
  }
  return schemas
}

/**
 * Build one entity operation schema with reusable field definitions.
 * @param entity - Entity definition.
 * @param kind - Operation kind.
 * @param definitions - Canonical definitions.
 * @returns Self-contained JSON Schema.
 */
function entitySchema(
  entity: EntityDefinition,
  kind: SchemaKind,
  definitions: Graph['definitions'],
): Readonly<Record<string, unknown>> {
  const defs: Record<string, unknown> = {}
  const reference = (target: string): string => {
    const key = identityKey(target)
    defs[key] ??= identityDefinition(target, definitions)
    return `#/$defs/${key}`
  }
  for (const owner of definitions.ancestry(entity.name)) {
    if (owner === 'Entity') {
      defs[nameKey(kind)] = { type: 'string' }
      if (kind === 'output') {
        defs[fieldKey('Entity', 'lastUpdatedAt', 'output')] = {
          anyOf: [{ format: 'date-time', type: 'string' }, { type: 'null' }],
        }
        defs[fieldKey('Entity', 'lastUpdatedBy', 'output')] = {
          anyOf: [{ $ref: reference('User') }, { type: 'null' }],
        }
      }
      continue
    }
    const ownerEntity = definitions.entity(owner)
    if (!ownerEntity) continue
    for (const field of ownerEntity.fields) {
      if (field.type === FieldType.Inverse || field.name === 'id') continue
      if (kind !== 'output' && GENERATED_FIELDS.has(field.name)) continue
      defs[fieldKey(owner, field.name, kind)] = fieldSchema(field, kind, definitions, reference)
    }
  }
  const properties: Record<string, unknown> = {}
  const required = requiredFields(entity, kind)
  if (kind !== 'update') properties.id = identitySchema(entity.idFormat)
  if (kind === 'output') properties.entity = discriminatorSchema(entity, definitions)
  properties.name = { $ref: `#/$defs/${nameKey(kind)}` }
  for (const field of entity.effectiveFields) {
    if (field.name === 'id' || field.name === 'name' || field.name === 'entity') continue
    if (kind !== 'output' && GENERATED_FIELDS.has(field.name)) continue
    properties[field.name] = { $ref: `#/$defs/${fieldKey(field.owner, field.name, kind)}` }
  }
  return {
    $defs: defs,
    additionalProperties: false,
    properties,
    ...(required.length === 0 ? {} : { required }),
    type: 'object',
  }
}

/**
 * Render one operation's required properties.
 * @param entity - Entity definition.
 * @param kind - Operation kind.
 * @returns Required property names.
 */
function requiredFields(entity: EntityDefinition, kind: SchemaKind): readonly string[] {
  if (kind === 'update') return []
  const required = entity.effectiveFields
    .filter(field => field.name !== 'id' && field.name !== 'entity')
    .filter(field => field.name !== 'lastUpdatedAt' && field.name !== 'lastUpdatedBy')
    .filter(field => field.default === undefined && (
      field.type === FieldType.Entity ? field.nullable === false : field.nullable !== true
    ))
    .map(field => field.name)
  const identity = kind === 'output' ? ['id', 'entity'] : []
  return kind === 'create' && entity.idFormat === 'Snowflake'
    ? ['id', ...required]
    : [...identity, ...required]
}

/**
 * Render one field's JSON Schema.
 * @param field - Field definition.
 * @param kind - Operation kind.
 * @param definitions - Canonical definitions.
 * @param reference - Register one identity definition.
 * @returns JSON Schema fragment.
 */
function fieldSchema(
  field: FieldDefinition,
  kind: SchemaKind,
  definitions: Graph['definitions'],
  reference: (target: string) => string,
): Record<string, unknown> {
  if (field.type === FieldType.Inverse) return {}
  if (field.type === FieldType.Entity) {
    if (kind !== 'output') {
      return field.nullable === false
        ? { type: 'string' }
        : { type: ['string', 'null'] }
    }
    const identity = { $ref: reference(field.target) }
    return field.nullable === false ? identity : { anyOf: [identity, { type: 'null' }] }
  }
  if (field.type === FieldType.Array) {
    return nullableSchema({
      items: schemaForScalar(field.items.type),
      type: 'array',
    }, field)
  }
  if (field.type === FieldType.JSON) {
    return field.nullable === true ? {} : { not: { type: 'null' } }
  }
  return nullableSchema({
    ...schemaForScalar(field.type),
    ...boundsFor(field),
  }, field)
}

/**
 * Allow null exactly when the canonical field is nullable.
 * @param schema - Non-null schema.
 * @param field - Field definition.
 * @param field.nullable - Whether the field accepts null.
 * @returns The field schema with its null union.
 */
function nullableSchema(
  schema: Record<string, unknown>,
  field: { readonly nullable?: boolean },
): Record<string, unknown> {
  return field.nullable === true
    ? { anyOf: [schema, { type: 'null' }] }
    : schema
}

/**
 * Render one entity identity reference schema.
 * @param target - Reference target entity, or `Entity`.
 * @param definitions - Canonical definitions.
 * @returns Reference identity schema.
 */
function identityDefinition(
  target: string,
  definitions: Graph['definitions'],
): Record<string, unknown> {
  if (target === 'Entity') {
    return {
      additionalProperties: false,
      properties: {
        entity: { type: 'string' },
        id: identitySchema(undefined),
        name: { type: 'string' },
      },
      required: ['id', 'name', 'entity'],
      type: 'object',
    }
  }
  return {
    additionalProperties: false,
    properties: {
      entity: discriminatorSchemaForTarget(target, definitions),
      id: identitySchema(definitions.entity(target)?.idFormat),
      name: { type: 'string' },
    },
    required: ['id', 'name', 'entity'],
    type: 'object',
  }
}

/**
 * Render the canonical root identity schema for one entity format.
 * @param format - Effective identity format, when refined.
 * @returns JSON Schema for the shared root `id` field.
 */
function identitySchema(
  format: 'Snowflake' | 'UUID' | undefined,
): Record<string, unknown> {
  if (format === 'UUID') return { pattern: UUID_IDENTITY_PATTERN, type: 'string' }
  if (format === 'Snowflake') {
    return { maxLength: 20, pattern: SNOWFLAKE_IDENTITY_PATTERN, type: 'string' }
  }
  return {
    anyOf: [
      { pattern: UUID_IDENTITY_PATTERN, type: 'string' },
      { maxLength: 20, pattern: SNOWFLAKE_IDENTITY_PATTERN, type: 'string' },
    ],
  }
}

/**
 * Render canonical scalar bounds as JSON Schema keywords.
 * @param field - Effective scalar field.
 * @returns JSON Schema bounds.
 */
function boundsFor(field: EffectiveFieldDefinition | FieldDefinition): Record<string, number> {
  if (field.type !== FieldType.Number && field.type !== FieldType.String) return {}
  return {
    ...(field.type === FieldType.Number && field.maximum !== undefined ? { maximum: field.maximum } : {}),
    ...(field.type === FieldType.Number && field.minimum !== undefined ? { minimum: field.minimum } : {}),
    ...(field.type === FieldType.String && field.maxLength !== undefined ? { maxLength: field.maxLength } : {}),
    ...(field.type === FieldType.String && field.minLength !== undefined ? { minLength: field.minLength } : {}),
  }
}

/**
 * Render the output discriminator for one concrete or abstract entity.
 * @param entity - Entity whose output is being described.
 * @param definitions - Canonical definitions.
 * @returns JSON Schema for the entity discriminator.
 */
function discriminatorSchema(
  entity: EntityDefinition,
  definitions: Graph['definitions'],
): Record<string, unknown> {
  if (!entity.abstract) return { const: entity.name, type: 'string' }
  return discriminatorSchemaForTarget(entity.name, definitions)
}

/**
 * Render a concrete-discriminator schema for a reference target.
 * @param target - Referenced entity name.
 * @param definitions - Canonical definitions.
 * @returns JSON Schema for the target discriminator.
 */
function discriminatorSchemaForTarget(
  target: string,
  definitions: Graph['definitions'],
): Record<string, unknown> {
  if (target === 'Entity') return { type: 'string' }
  const entity = definitions.entity(target)
  if (!entity || !entity.abstract) return { const: target, type: 'string' }
  const descendants = definitions.concreteDescendants(target).map(descendant => descendant.name)
  return descendants.length === 0
    ? { type: 'string' }
    : { enum: descendants, type: 'string' }
}

/**
 * Render one scalar JSON Schema.
 * @param type - Scalar field type.
 * @returns JSON Schema fragment.
 */
function schemaForScalar(type: ScalarFieldDefinition['type']): Record<string, unknown> {
  switch (type) {
    case FieldType.Boolean: return { type: 'boolean' }
    case FieldType.Number: return { type: 'number' }
    case FieldType.String: return { type: 'string' }
    case FieldType.Date: return { format: 'date', type: 'string' }
    case FieldType.Timestamp: return { format: 'date-time', type: 'string' }
    case FieldType.ID: return { type: 'string' }
    default: return {}
  }
}

/**
 * Render one field definition key.
 * @param owner - Field owner.
 * @param name - Field name.
 * @param kind - Operation kind.
 * @returns Safe definition key.
 */
function fieldKey(owner: string, name: string, kind: SchemaKind): string {
  return `${owner}_${name}_${kind}`
}

/**
 * Render the root name definition key.
 * @param kind - Operation kind.
 * @returns Definition key.
 */
function nameKey(kind: SchemaKind): string {
  return fieldKey('Entity', 'name', kind)
}

/**
 * Render one identity definition key.
 * @param target - Reference target.
 * @returns Definition key.
 */
function identityKey(target: string): string {
  return `${target}_Identity`
}

/**
 * Generate the JSON Schema emitter file set.
 * @param graph - Canonical application Graph.
 * @returns One generated JSON Schema file.
 */
export function jsonSchemaOutput(graph: Graph): readonly EmittedFile[] {
  return [{
    content: `${JSON.stringify(generateJSONSchemas(graph), null, 2)}\n`,
    name: 'schemas',
  }]
}

/** Independently owned JSON Schema emitter. */
export const JsonSchemaEmitter = emitter(
  { extension: 'json', folder: 'json-schema' },
  jsonSchemaOutput,
)

// Emitter modules are discovered and invoked by their default export.
export default JsonSchemaEmitter
