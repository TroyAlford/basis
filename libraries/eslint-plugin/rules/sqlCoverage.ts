/**
 * Calculate corpus and schema coverage.
 * @returns Coverage counts and percentages.
 */
export function sqlCoverage(): {
  corpusCovered: number,
  corpusPercent: number,
  schemaCovered: number,
  schemaPercent: number,
} {
  const corpusNodes = [...SQL_CORPUS_NODE_TYPES, ...PL_CORPUS_NODE_TYPES]
  const corpusCovered = corpusNodes.filter(node => (
    SQL_IMPLEMENTED_NODE_TYPES.has(node) || PL_IMPLEMENTED_NODE_TYPES.has(node)
  )).length
  const schemaCovered = SQL_SCHEMA_NODE_TYPES.filter(node => SQL_NODE_STATUS.get(node) === 'implemented').length
  return {
    corpusCovered,
    corpusPercent: corpusNodes.length === 0 ? 100 : Math.round((corpusCovered / corpusNodes.length) * 100),
    schemaCovered,
    schemaPercent: Math.round((schemaCovered / SQL_SCHEMA_NODE_TYPES.length) * 100),
  }
}
