/** Coverage calculated from an executable corpus report. */
export interface CoverageSummary {
  corpusCovered: number,
  corpusPercent: number,
  schemaCovered: number,
  schemaPercent: number,
  unimplemented: readonly string[],
}

/**
 * Calculate coverage from a corpus report.
 * @param report - Executable corpus report.
 * @returns Coverage summary.
 */
export function sqlCoverage(report: CorpusReport): CoverageSummary {
  const corpusNodes = [...report.nodes.keys()]
  const unimplemented = SQL_SCHEMA_NODE_TYPES.filter(node => !report.nodes.has(node))
  return {
    corpusCovered: corpusNodes.length,
    corpusPercent: report.unsupported.length === 0 && report.parseFailures.length === 0 ? 100 : 0,
    schemaCovered: corpusNodes.length,
    schemaPercent: Math.round((corpusNodes.length / SQL_SCHEMA_NODE_TYPES.length) * 100),
    unimplemented,
  }
}
