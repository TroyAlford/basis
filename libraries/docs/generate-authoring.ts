#!/usr/bin/env bun
import { mkdir, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { Cardinality, defineEntities, generateProducts } from '../server/source/Authoring'
import { FieldType } from '../server/source/EntityDefinitions'

const entities = defineEntities({
  entities: [
    {
      fields: [
        { field: 'email', type: FieldType.String },
        {
          cardinality: Cardinality.Many,
          field: 'notes',
          inverse: 'owner',
          target: 'Note',
          type: FieldType.Inverse,
        },
      ],
      name: 'User',
    },
    {
      fields: [
        { field: 'title', type: FieldType.String },
        { field: 'owner', inverse: 'notes', target: 'User', type: FieldType.Entity },
        { field: 'tags', items: { type: FieldType.String }, type: FieldType.Array },
        { field: 'metadata', type: FieldType.JSON },
      ],
      name: 'Note',
    },
  ],
})

const products = generateProducts(entities)
const output = resolve(import.meta.dir, 'generated', 'Authoring.generated.ts')
await mkdir(resolve(import.meta.dir, 'generated'), { recursive: true })
await writeFile(output, `/* eslint-disable */
/** Generated by libraries/docs/generate-authoring.ts. Do not edit. */

export const authoringTypes = ${JSON.stringify(products.types)}
export const authoringSchema = ${JSON.stringify(JSON.stringify(products.schemas.Note?.output, null, 2))}
export const authoringLogicalErd = ${JSON.stringify(products.logicalErd)}
export const authoringPhysicalErd = ${JSON.stringify(products.physicalErd)}
`)
process.stdout.write(`[basis] generated ${output}\n`)
